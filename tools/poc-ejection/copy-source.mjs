#!/usr/bin/env node
/**
 * SOURCE MODE'S COPY SCRIPT (#3408, plan item 3; owner decision Q32 A): copy the components' source into a client,
 * where the client owns it. The tokens are not copied: they stay the versioned `@prism3/tokens` package, so they
 * never fork per app.
 *
 *   node tools/poc-ejection/copy-source.mjs --from <prism3 checkout> --to <client>/src/prism3
 *
 * What it copies: each component package's published files (its `package.json` `files`), less the README, into
 * `<to>/css/` and `<to>/web-components/`. What it prints, as one JSON line: the files it copied and the runtime
 * dependencies the copies need (the element package's own `dependencies`, today Lit), which the client installs itself.
 *
 * THE ONE REWRITE (owner decision 3 on #4471, 2026-11-23): a file whose first line says "GENERATED by packages/…" has
 * that header replaced with a provenance line naming the package and version it was copied from. The header runs
 * from that first line through the line ending "do not edit; … regenerate" (one line in the elements, two in the CSS).
 * In a client the header was wrong twice: it names a generator the client doesn't have, and it says "do not edit"
 * about code the client now owns. Everything else is copied byte for byte, on purpose: what the copies still say about
 * prism3 is what the reference counter (`refs.ts`) measures, and rewriting more here would hide the measurement.
 * A file with no such header is copied byte for byte.
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const arg = (n) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : undefined; };
const from = arg('--from');
const to = arg('--to');
if (!from || !to) { console.error('usage: copy-source.mjs --from <prism3 checkout> --to <client>/src/prism3'); process.exit(2); }

const PACKAGES = { css: 'packages/css', 'web-components': 'packages/web-components' };

/**
 * The provenance line, in the header's own comment syntax. DRAFT wording, held for the owner (#4471 decision 3). A
 * CSS header's comment goes on past the header (its next line starts ` * `), so the line opens the same comment.
 */
const provenance = (open, pkg, version, file) =>
  `${open} Copied from ${pkg}@${version} (${file}). This copy is yours to edit; prism3 no longer regenerates it.`;

/** The text with its generated header swapped for the provenance line, or null when it has no generated header. */
const withProvenance = (text, pkg, version, file) => {
  const lines = text.split('\n');
  if (!/GENERATED by packages\//.test(lines[0])) return null;
  const end = lines.findIndex((l) => /do not edit;.*regenerate/i.test(l));
  if (end < 0 || end > 2) throw new Error(`${file}: its GENERATED header has no "do not edit; … regenerate" within three lines`);
  const open = /^\s*(\/\*|\/\/)/.exec(lines[0])?.[1];
  if (!open) throw new Error(`${file}: its GENERATED header opens with neither /* nor //`);
  return [provenance(open, pkg, version, file), ...lines.slice(end + 1)].join('\n');
};
const copied = [];
const dependencies = {};
for (const [dest, dir] of Object.entries(PACKAGES)) {
  const pj = JSON.parse(readFileSync(resolve(from, dir, 'package.json'), 'utf8'));
  mkdirSync(join(to, dest), { recursive: true });
  for (const f of pj.files.filter((x) => x !== 'README.md')) {
    const src = resolve(from, dir, f);
    const rewritten = withProvenance(readFileSync(src, 'utf8'), pj.name, pj.version, f);
    if (rewritten === null) copyFileSync(src, join(to, dest, f));
    else writeFileSync(join(to, dest, f), rewritten);
    copied.push(`${dest}/${f}`);
  }
  Object.assign(dependencies, pj.dependencies ?? {});
}
console.log(JSON.stringify({ copied, dependencies }));
